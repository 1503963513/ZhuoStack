/**
 * 根据图标名称安全获取对应的 LucideIcon 组件
 * 遇到未知或未配置的名称，默认兜底为 FileText
 */
export function getDynamicIcon(name?: string | null, fallback: LucideIcon = FileText): LucideIcon {
  if (!name || !GLOBAL_ICON_MAP[name]) return fallback;
  return GLOBAL_ICON_MAP[name];
}

interface DynamicIconProps extends Omit<LucideProps, "name"> {
  name?: string | null;
  fallback?: LucideIcon;
}

/**
 * 通用动态图标渲染组件
 */
export function DynamicIcon({ name, fallback = FileText, ...props }: DynamicIconProps) {
  const IconComponent = (name && GLOBAL_ICON_MAP[name]) ? GLOBAL_ICON_MAP[name] : fallback;
  return <IconComponent {...props} />;
}
